-- ============================================================================
-- ShelfLog (Personal Video Game Tracker) — Supabase Schema, RLS & Storage
-- ============================================================================

-- 1. Main CRUD Table: public.games
create table if not exists public.games (
  id bigint generated by default as identity primary key,
  title text not null,
  platform text not null default 'PC',
  genre text not null default 'Action',
  status text not null default 'Backlog' check (status in ('Backlog', 'Playing', 'Completed', 'Dropped')),
  release_year integer,
  hours_played numeric(6,1) not null default 0,
  rating integer not null default 0 check (rating between 0 and 5),
  description text default '',
  specs text[] not null default '{}',
  notes text[] not null default '{}',
  cover_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. Favorites Table: public.game_favorites
create table if not exists public.game_favorites (
  id bigint generated by default as identity primary key,
  game_id bigint not null references public.games(id) on delete cascade,
  user_id uuid not null,
  created_at timestamptz not null default now(),
  unique (game_id, user_id)
);

-- 3. Play Logs / Reviews Table: public.game_logs
create table if not exists public.game_logs (
  id bigint generated by default as identity primary key,
  game_id bigint not null references public.games(id) on delete cascade,
  user_id uuid not null,
  author_name text not null default 'Player',
  rating integer not null check (rating between 1 and 5),
  hours_logged numeric(5,1) not null default 0,
  comment text default '',
  created_at timestamptz not null default now()
);

-- 4. Enable Row Level Security (RLS)
alter table public.games enable row level security;
alter table public.game_favorites enable row level security;
alter table public.game_logs enable row level security;

-- 5. Public Policies (App uses anonymous client UUIDs without Supabase Auth)
drop policy if exists "Allow public read games" on public.games;
create policy "Allow public read games" on public.games for select using (true);

drop policy if exists "Allow public insert games" on public.games;
create policy "Allow public insert games" on public.games for insert with check (true);

drop policy if exists "Allow public update games" on public.games;
create policy "Allow public update games" on public.games for update using (true) with check (true);

drop policy if exists "Allow public delete games" on public.games;
create policy "Allow public delete games" on public.games for delete using (true);

drop policy if exists "Allow public access favorites" on public.game_favorites;
create policy "Allow public access favorites" on public.game_favorites for all using (true) with check (true);

drop policy if exists "Allow public access logs" on public.game_logs;
create policy "Allow public access logs" on public.game_logs for all using (true) with check (true);

-- 6. Storage Bucket for Game Covers
insert into storage.buckets (id, name, public)
values ('game-covers', 'game-covers', true)
on conflict (id) do update set public = true;

drop policy if exists "Public read game covers" on storage.objects;
create policy "Public read game covers" on storage.objects
  for select using (bucket_id = 'game-covers');

drop policy if exists "Public upload game covers" on storage.objects;
create policy "Public upload game covers" on storage.objects
  for insert with check (bucket_id = 'game-covers');

drop policy if exists "Public update game covers" on storage.objects;
create policy "Public update game covers" on storage.objects
  for update using (bucket_id = 'game-covers') with check (bucket_id = 'game-covers');

drop policy if exists "Public delete game covers" on storage.objects;
create policy "Public delete game covers" on storage.objects
  for delete using (bucket_id = 'game-covers');

